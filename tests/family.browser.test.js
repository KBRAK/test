import test from 'node:test';
import assert from 'node:assert/strict';
import { browserEnabled, withBrowser } from './helpers/browser.js';
import { createAppServer } from '../server.js';
import { createFamilyStore } from '../backend/family-store.js';

test('Browser: Familienprofile, persönliche Kalender, Übernahme und Gerätekonflikte', {skip:!browserEnabled,timeout:45000}, async()=>{
  const store=createFamilyStore(':memory:'), accessKey='browser-family-test-key';
  const server=createAppServer({store,accessKey});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const url='http://127.0.0.1:'+server.address().port;
  try {
    await withBrowser(url,async({command,evaluate,waitFor})=>{
      await waitFor(`document.querySelector('[data-family-form="connect"]')`);
      await evaluate(`window.confirm=()=>true;
        window.fill=(form,values)=>{const target=document.querySelector('[data-family-form="'+form+'"]');for(const [name,value] of Object.entries(values)){const field=target.elements.namedItem(name);field.value=value;field.dispatchEvent(new Event('input',{bubbles:true}));}};
        window.submit=form=>document.querySelector('[data-family-form="'+form+'"]').requestSubmit();
        fill('connect',{key:${JSON.stringify(accessKey)}});submit('connect');`);
      await waitFor(`document.querySelector('[data-family-form="member"]')`);
      await evaluate(`fill('member',{firstName:'Mia',lastName:'Müller',birthDate:'2020-02-29',foodLikes:'Nudeln, Äpfel',intolerances:'Milch',institutionType:'school',institutionName:'Grundschule',foodNotes:'Nicht scharf'});submit('member');`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Familienprofil gespeichert.'`);
      let snapshot=store.snapshot(); assert.equal(snapshot.members.length,1); const mia=snapshot.members[0];
      assert.equal(mia.institutionName,'Grundschule'); assert.deepEqual(mia.intolerances,['Milch']);
      await evaluate(`fill('member',{notes:'Noch nicht gespeichert'});
        fill('event',{title:'Unterricht',startDate:'2026-11-02',endDate:'2027-06-30',startTime:'08:00',endTime:'13:00',departureTime:'07:30'});submit('event');`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Termin gespeichert.'`);
      assert.equal(await evaluate(`document.querySelector('[data-family-form="member"]').elements.notes.value`),'Noch nicht gespeichert');
      assert.equal(store.snapshot().events[0].memberId,mia.id);
      await evaluate(`document.querySelector('[data-family-week]').value='2026-11-02';document.querySelector('[data-family-week]').dispatchEvent(new Event('change',{bubbles:true}));`);
      assert.equal(await evaluate(`document.querySelectorAll('.calendar-day li').length`),5);
      assert.equal(await evaluate(`document.querySelector('.calendar-day').textContent.includes('Losgehen 07:30')`),true);
      await evaluate(`document.querySelector('[data-family-action="new-member"]').click();`);
      await evaluate(`fill('member',{firstName:'Tom'});submit('member');`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Familienprofil gespeichert.'`);
      const tom=store.snapshot().members.find(m=>m.firstName==='Tom');
      assert.equal(await evaluate(`document.querySelectorAll('.calendar-day li').length`),0);
      await evaluate(`fill('event',{title:'Fußball',kind:'sport',repeat:'once',startDate:'2026-11-07',startTime:'15:00',endTime:'16:00',departureTime:'14:30',location:'Sportverein'});submit('event');`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Termin gespeichert.'`);
      assert.equal(store.snapshot().events.find(v=>v.title==='Fußball').memberId,tom.id);
      await evaluate(`const select=document.querySelector('[data-family-calendar]');select.value='';select.dispatchEvent(new Event('change',{bubbles:true}));`);
      assert.equal(await evaluate(`document.querySelectorAll('.calendar-day li').length`),6);
      await evaluate(`document.querySelector('[data-family-action="select-member"][data-id="${mia.id}"]').click();`);
      assert.equal(await evaluate(`document.querySelectorAll('.calendar-day li').length`),5);
      store.updateMember(mia.id,{...store.snapshot().members.find(m=>m.id===mia.id),firstName:'Mia vom anderen Gerät'});
      await evaluate(`fill('member',{firstName:'Veraltete Änderung'});submit('member');`);
      await waitFor(`document.querySelector('#family-status')?.textContent.includes('anderen Gerät')`);
      assert.equal(store.snapshot().members.find(m=>m.id===mia.id).firstName,'Mia vom anderen Gerät');
      await evaluate(`document.querySelector('[data-family-action="refresh"]').click();`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Aktuelle Serverdaten geladen.'`);
      await evaluate(`localStorage.setItem('zuhause.household.v1',JSON.stringify({version:1,household:{name:'Familie',notes:''},inventory:[],shopping:[],residents:[{id:'legacy',name:'Alex',intolerances:['Nüsse']}]}));document.querySelector('[data-family-action="migrate"]').click();`);
      await waitFor(`document.querySelector('#family-status')?.textContent.startsWith('1 lokale Bewohner')`);
      assert.equal(store.snapshot().members.length,3);
      await evaluate(`document.querySelector('[data-family-action="migrate"]').click();`);
      await waitFor(`document.querySelector('#family-status')?.textContent.startsWith('0 lokale Bewohner')`);
      // Family backup uses the real download action and restores profiles plus calendars atomically.
      await evaluate(`window.familyBlob=null;window.oldCreate=URL.createObjectURL;window.oldClick=HTMLAnchorElement.prototype.click;
        URL.createObjectURL=blob=>{window.familyBlob=blob;return oldCreate(blob);};HTMLAnchorElement.prototype.click=function(){};
        document.querySelector('[data-family-action="backup"]').click();`);
      await waitFor('window.familyBlob !== null');
      const backup=await evaluate('(async()=>JSON.parse(await familyBlob.text()))()');
      assert.equal(backup.members.length,3); assert.equal(backup.events.length,2);
      await evaluate(`URL.createObjectURL=oldCreate;HTMLAnchorElement.prototype.click=oldClick;
        window.savedFamilyBackup=${JSON.stringify(backup)};
        window.restoreFile=text=>{const transfer=new DataTransfer();transfer.items.add(new File([text],'family.json',{type:'application/json'}));document.querySelector('[data-family-form="restore"]').elements.file.files=transfer.files;submit('restore');};
        restoreFile(JSON.stringify({...savedFamilyBackup,format:'wrong'}));`);
      await waitFor(`document.querySelector('#family-status')?.textContent.includes('Familienbackup auswählen')`);
      assert.equal(store.snapshot().members.length,3);
      await evaluate(`window.confirm=()=>false;restoreFile(JSON.stringify(savedFamilyBackup));`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Wiederherstellung abgebrochen.'`);
      await evaluate(`window.confirm=()=>true;restoreFile(JSON.stringify(savedFamilyBackup));`);
      await waitFor(`document.querySelector('#family-status')?.textContent==='Familienbackup wiederhergestellt.'`);
      assert.equal(store.snapshot().events.length,2);
      await evaluate(`document.querySelector('[data-family-action="migrate"]').click();`);
      await waitFor(`document.querySelector('#family-status')?.textContent.startsWith('0 lokale Bewohner')`);
      assert.equal(store.snapshot().members.length,3);
      await command('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
      assert.equal(await evaluate('document.documentElement.scrollWidth <= document.documentElement.clientWidth'),true);
    });
  } finally {server.closeAllConnections();await new Promise(resolve=>server.close(resolve));store.close();}
});
